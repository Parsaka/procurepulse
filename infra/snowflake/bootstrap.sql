-- ProcurePulse: one-time Snowflake setup in the browser (Snowsight worksheet, role ACCOUNTADMIN).
-- Creates exactly what infra/snowflake/main.tf creates. Use either this file or Terraform, not both.
-- Before running: replace <PP_CI_PUBLIC_KEY> with the one line from keys/pp_ci.pub.txt
-- (python scripts/make_keypair.py pp_ci). Then select all and press "Run all".

USE ROLE ACCOUNTADMIN;

-- Storage -------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS PROCUREPULSE DATA_RETENTION_TIME_IN_DAYS = 1
  COMMENT = 'ProcurePulse: SAP purchase-to-pay process mining (BPI Challenge 2019)';
CREATE SCHEMA IF NOT EXISTS PROCUREPULSE.RAW          COMMENT = 'SAP tables as landed by the loader';
CREATE SCHEMA IF NOT EXISTS PROCUREPULSE.STAGING      COMMENT = 'dbt staging views';
CREATE SCHEMA IF NOT EXISTS PROCUREPULSE.INTERMEDIATE COMMENT = 'dbt intermediate: event log';
CREATE SCHEMA IF NOT EXISTS PROCUREPULSE.MARTS        COMMENT = 'dbt marts: star schema and KPI marts';
CREATE SCHEMA IF NOT EXISTS PROCUREPULSE.REFERENCE    COMMENT = 'dbt seeds';
CREATE SCHEMA IF NOT EXISTS PROCUREPULSE.ANALYTICS    COMMENT = 'Python outputs';

-- Compute: XS warehouse, suspends after 60 s, hard monthly credit ceiling -------
CREATE RESOURCE MONITOR IF NOT EXISTS PP_MONTHLY_MONITOR
  WITH CREDIT_QUOTA = 5 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO NOTIFY
           ON 80 PERCENT DO NOTIFY
           ON 90 PERCENT DO SUSPEND
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;
CREATE WAREHOUSE IF NOT EXISTS PP_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  RESOURCE_MONITOR = PP_MONTHLY_MONITOR COMMENT = 'ProcurePulse loads, dbt runs and BI queries';

-- Roles ------------------------------------------------------------------------
CREATE ROLE IF NOT EXISTS PP_LOADER;
CREATE ROLE IF NOT EXISTS PP_TRANSFORMER;
CREATE ROLE IF NOT EXISTS PP_REPORTER;
CREATE ROLE IF NOT EXISTS PP_COPILOT_RO;
GRANT ROLE PP_LOADER      TO ROLE SYSADMIN;
GRANT ROLE PP_TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE PP_REPORTER    TO ROLE SYSADMIN;
GRANT ROLE PP_COPILOT_RO  TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE PP_WH TO ROLE PP_LOADER;
GRANT USAGE ON WAREHOUSE PP_WH TO ROLE PP_TRANSFORMER;
GRANT USAGE ON WAREHOUSE PP_WH TO ROLE PP_REPORTER;
GRANT USAGE ON WAREHOUSE PP_WH TO ROLE PP_COPILOT_RO;
GRANT USAGE ON DATABASE PROCUREPULSE TO ROLE PP_LOADER;
GRANT USAGE ON DATABASE PROCUREPULSE TO ROLE PP_TRANSFORMER;
GRANT USAGE ON DATABASE PROCUREPULSE TO ROLE PP_REPORTER;
GRANT USAGE ON DATABASE PROCUREPULSE TO ROLE PP_COPILOT_RO;

-- Loader: write RAW only
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA PROCUREPULSE.RAW TO ROLE PP_LOADER;

-- Transformer: read RAW, build the dbt and analytics schemas
GRANT USAGE ON SCHEMA PROCUREPULSE.RAW TO ROLE PP_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA PROCUREPULSE.RAW TO ROLE PP_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROCUREPULSE.RAW TO ROLE PP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT ON SCHEMA PROCUREPULSE.STAGING      TO ROLE PP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT ON SCHEMA PROCUREPULSE.INTERMEDIATE TO ROLE PP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT ON SCHEMA PROCUREPULSE.MARTS        TO ROLE PP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT ON SCHEMA PROCUREPULSE.REFERENCE    TO ROLE PP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT ON SCHEMA PROCUREPULSE.ANALYTICS    TO ROLE PP_TRANSFORMER;

-- Readers: MARTS and ANALYTICS only
GRANT USAGE ON SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_REPORTER;
GRANT USAGE ON SCHEMA PROCUREPULSE.ANALYTICS TO ROLE PP_REPORTER;
GRANT USAGE ON SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_COPILOT_RO;
GRANT USAGE ON SCHEMA PROCUREPULSE.ANALYTICS TO ROLE PP_COPILOT_RO;
GRANT SELECT ON ALL TABLES    IN SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_REPORTER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_REPORTER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_REPORTER;
GRANT SELECT ON ALL TABLES    IN SCHEMA PROCUREPULSE.ANALYTICS TO ROLE PP_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROCUREPULSE.ANALYTICS TO ROLE PP_REPORTER;
GRANT SELECT ON ALL TABLES    IN SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_COPILOT_RO;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_COPILOT_RO;
GRANT SELECT ON ALL VIEWS     IN SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_COPILOT_RO;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PROCUREPULSE.MARTS     TO ROLE PP_COPILOT_RO;
GRANT SELECT ON ALL TABLES    IN SCHEMA PROCUREPULSE.ANALYTICS TO ROLE PP_COPILOT_RO;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PROCUREPULSE.ANALYTICS TO ROLE PP_COPILOT_RO;

-- CI service user: key-pair only, no password ---------------------------------
CREATE USER IF NOT EXISTS PP_CI
  TYPE = SERVICE
  DEFAULT_WAREHOUSE = PP_WH DEFAULT_ROLE = PP_TRANSFORMER
  RSA_PUBLIC_KEY = '<PP_CI_PUBLIC_KEY>'
  COMMENT = 'GitHub Actions: loads RAW and runs dbt';
GRANT ROLE PP_LOADER      TO USER PP_CI;
GRANT ROLE PP_TRANSFORMER TO USER PP_CI;

-- The value for the GitHub secret SNOWFLAKE_ACCOUNT (orgname-accountname):
SELECT CURRENT_ORGANIZATION_NAME() || '-' || CURRENT_ACCOUNT_NAME() AS snowflake_account;
